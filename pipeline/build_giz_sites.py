def main():
    out_img = os.path.join(DOCS, "assets", "sites")
    os.makedirs(out_img, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(["pdfimages", "-j", "-p", "-f", "3", "-l", "95", PDF, os.path.join(tmp, "im")], check=True)
        rows = []
        for s in SITES:
            sid = s.get("label") or str(int(s["n"]))
            photos = []
            for k, (ref, cap) in enumerate(s.pop("figs")):
                im = Image.open(os.path.join(tmp, f"im-{ref}.jpg")).convert("RGB")
                im.thumbnail((1100, 1100))
                name = f"site{sid}-{k + 1}.jpg"
                im.save(os.path.join(out_img, name), quality=76, optimize=True, progressive=True)
                photos.append({"src": f"assets/sites/{name}", "cap": cap})
            s["id"] = sid
            s["photos"] = photos
            s.pop("n")
            s.pop("label", None)
            rows.append(s)
    with open(os.path.join(DOCS, "data", "giz_sites.json"), "w") as f:
        json.dump({"source": REPORT, "sites": rows}, f, ensure_ascii=False, separators=(",", ":"))
    print(len(rows), "sites")


main()
